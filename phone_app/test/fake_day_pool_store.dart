import 'package:crdt_sync/crdt_sync.dart';

/// An in-memory `LogPersistence`.
class MemPersistence implements LogPersistence {
  /// The persisted text, or null before the first write.
  String? text;

  @override
  Future<String?> read() async => text;

  @override
  Future<void> write(String value) async => text = value;
}

/// An in-memory `RemoteStore`: a flat path -> text map.
class MemRemote implements RemoteStore {
  /// Every file, by full path.
  final Map<String, String> files = {};

  @override
  Future<List<String>> listDirectory(String path) async {
    final prefix = '$path/';
    return files.keys
        .where((k) => k.startsWith(prefix))
        .map((k) => k.substring(prefix.length).split('/').first)
        .toSet()
        .toList();
  }

  @override
  Future<String?> getFileText(String path) async => files[path];

  @override
  Future<void> putFileText(
    String path,
    String text, {
    required String message,
  }) async => files[path] = text;

  @override
  Future<void> deleteFile(String path, {String? message}) async =>
      files.remove(path);

  @override
  Future<bool> canAccessRemote() async => true;

  @override
  void close() {}
}

/// A remote that is offline for every read and write.
class BrokenRemote implements RemoteStore {
  @override
  Future<List<String>> listDirectory(String path) async =>
      throw RemoteSyncError('offline');

  @override
  Future<String?> getFileText(String path) async =>
      throw RemoteSyncError('offline');

  @override
  Future<void> putFileText(
    String path,
    String text, {
    required String message,
  }) async => throw RemoteSyncError('offline');

  @override
  Future<void> deleteFile(String path, {String? message}) async {}

  @override
  Future<bool> canAccessRemote() async => false;

  @override
  void close() {}
}

